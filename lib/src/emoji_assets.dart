/// The asset for one emoji, or null when the app doesn't carry it.
String? emojiAsset(String emoji) {
  final key = emoji.runes
      .where((rune) => rune != 0xfe0f)
      .map((rune) => rune.toRadixString(16))
      .join('-');
  return bundledEmoji.contains(key) ? 'assets/emoji/$key.webp' : null;
}

/// [emoji] drawn from the app's emoji pictures, a pair (🐕🗣️) side by side;
/// the phone's own emoji font when the app lacks any of them.
class EmojiImage extends StatelessWidget {
  const EmojiImage(this.emoji, {super.key, required this.size});

  final String emoji;
  final double size;

  @override
  Widget build(BuildContext context) {
    final parts = emoji.trim().characters.toList();
    final assets = [for (final part in parts) emojiAsset(part)];
    if (parts.isEmpty || parts.length > 3 || assets.contains(null)) {
      return Text(emoji, style: TextStyle(fontSize: size * 0.92, height: 1.1));
    }
    final each = parts.length == 1 ? size : size * 0.62;
    // Shrinks to fit a smaller box, such as a chip's 18 px avatar.
    return Semantics(
      label: emoji,
      child: FittedBox(
        fit: BoxFit.scaleDown,
        child: Row(mainAxisSize: MainAxisSize.min, children: [
          for (final asset in assets)
            Image.asset(asset!, width: each, height: each, filterQuality: FilterQuality.medium),
        ]),
      ),
    );
  }
}
