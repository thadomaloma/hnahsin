"""Turns the translations in l10n/<code>.json (id → text, the ids of
lib/src/app_text.dart plus game.<game>.<field> for the games' text) into
lib/l10n/strings_<code>.dart and lib/l10n/translations.dart.

    python3 tool/gen_l10n.py
"""
import glob
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def dart(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'").replace('\n', '\\n').replace('$', '\\$') + "'"


def main():
    codes = []
    for path in sorted(glob.glob(os.path.join(ROOT, 'l10n', '*.json'))):
        code = os.path.basename(path)[:-5]
        texts = json.load(open(path, encoding='utf-8'))
        name = 'strings' + ''.join(part.capitalize() for part in code.split('_'))
        lines = ['// Generated by tool/gen_l10n.py from l10n/%s.json. Edit that file, not this one.' % code,
                 '', 'const %s = <String, String>{' % name]
        lines += ['  %s: %s,' % (dart(k), dart(v)) for k, v in texts.items()]
        lines += ['};', '']
        open(os.path.join(ROOT, 'lib', 'l10n', 'strings_%s.dart' % code), 'w', encoding='utf-8').write('\n'.join(lines))
        codes.append((code, name))
    out = ['// Generated by tool/gen_l10n.py. Edit l10n/<code>.json, not this file.', '']
    out += ["import 'strings_%s.dart';" % code for code, _ in codes]
    out += ['', '/// Every translation by language code ([AppLocale.code]).',
            'const translations = <String, Map<String, String>>{']
    out += ['  %s: %s,' % (dart(code), name) for code, name in codes]
    out += ['};', '']
    open(os.path.join(ROOT, 'lib', 'l10n', 'translations.dart'), 'w', encoding='utf-8').write('\n'.join(out))
    print(len(codes), 'languages')


if __name__ == '__main__':
    main()
